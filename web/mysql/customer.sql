DROP TABLE IF EXISTS `customer`;

CREATE TABLE `customer` (
  `id` int(11) NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `customer_name` varchar(50) NOT NULL COMMENT '客户姓名',
  `wear_time` date DEFAULT NULL COMMENT '戴牙时间',
  `preparation_time` date DEFAULT NULL COMMENT '备牙时间',
  `expected_cut_time` date DEFAULT NULL COMMENT '预计截牙时间',
  `doctor` varchar(50) DEFAULT NULL COMMENT '医生（宇医生、秦医生、蔡医生等）',
  `material` varchar(500) DEFAULT NULL COMMENT '材料（支持多选，逗号分隔）',
  `image` varchar(255) DEFAULT NULL COMMENT '图片URL',
  `qr_code` varchar(255) DEFAULT NULL COMMENT '二维码图片URL',
  `remark` varchar(500) DEFAULT NULL COMMENT '备注',
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`),
  KEY `idx_customer_name` (`customer_name`),
  KEY `idx_doctor` (`doctor`),
  KEY `idx_wear_time` (`wear_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='客户进度表';

